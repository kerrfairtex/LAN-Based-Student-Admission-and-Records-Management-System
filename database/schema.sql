CREATE TABLE trac_jhs_sarms.transfer_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    direction VARCHAR(10) NOT NULL CHECK (direction IN ('incoming', 'outgoing')),
    counterpart_school VARCHAR(200) NOT NULL,
    request_date DATE NOT NULL,
    first_attendance_date DATE NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('pending', 'documents_sent', 'documents_received', 'completed', 'escalated')) DEFAULT 'pending',
    notes TEXT NULL,
    escalated_at TIMESTAMPTZ NULL,
    completed_at TIMESTAMPTZ NULL,
    created_by INTEGER NOT NULL,
    updated_by INTEGER NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT fk_transfer_student FOREIGN KEY (student_id) REFERENCES trac_jhs_sarms.students(id),
    CONSTRAINT fk_transfer_created_by FOREIGN KEY (created_by) REFERENCES trac_jhs_sarms.users(id),
    CONSTRAINT fk_transfer_updated_by FOREIGN KEY (updated_by) REFERENCES trac_jhs_sarms.users(id)
);
CREATE INDEX idx_transfer_status ON trac_jhs_sarms.transfer_requests (status);
CREATE INDEX idx_transfer_student ON trac_jhs_sarms.transfer_requests (student_id);

CREATE TRIGGER trg_transfer_requests_updated_at
